create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create type public.message_role as enum ('user', 'assistant', 'system');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_display_name_length check (char_length(display_name) <= 80)
);

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'Nova conversa',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint conversations_title_length check (char_length(title) between 1 and 80),
  constraint conversations_id_user_unique unique (id, user_id)
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.message_role not null,
  content text not null,
  created_at timestamptz not null default now(),
  constraint messages_content_length check (char_length(content) between 1 and 50000),
  constraint messages_conversation_owner_fk foreign key (conversation_id, user_id)
    references public.conversations(id, user_id) on delete cascade
);

create table public.rate_limits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index conversations_user_updated_idx on public.conversations (user_id, updated_at desc);
create index conversations_user_created_idx on public.conversations (user_id, created_at desc);
create index messages_conversation_created_idx on public.messages (conversation_id, created_at asc);
create index messages_user_idx on public.messages (user_id);
create index rate_limits_user_created_idx on public.rate_limits (user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.rate_limits enable row level security;

revoke all on table public.profiles, public.conversations, public.messages, public.rate_limits from anon, authenticated;
revoke all on sequence public.rate_limits_id_seq from anon, authenticated;

grant select, update on table public.profiles to authenticated;
grant select, insert, update, delete on table public.conversations to authenticated;
grant select, insert, update, delete on table public.messages to authenticated;

